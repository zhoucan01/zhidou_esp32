"""Calibrate independent heating/cooling tables for all three NTC channels."""
import argparse
import csv
import math
import re
from bisect import bisect_left, bisect_right
from datetime import datetime, timedelta
from pathlib import Path
from statistics import mean

from calibrate import make_table, predict

CHANNELS = (("NTC1", "NTC1_ADC"), ("NTC2", "NTC2_ADC"), ("NTC3", "NTC3_ADC"))
MAX_REFERENCE_GAP_SECONDS = 2.0
MOTOR_STOP_SETTLE_SECONDS = 0.2
COOLING_MOTOR_STOP_SETTLE_SECONDS = 0.5
MAX_RPM_SAMPLE_GAP_SECONDS = 0.5
MAX_COOLING_REFERENCE_SLOPE_C_PER_SECOND = -0.002


def parse_time(value):
    return datetime.fromisoformat(value)


def read_phases(csv_path, serial_path):
    serial = serial_path.read_text(encoding="utf-8", errors="replace")
    starts = [parse_time(value) for value in re.findall(
        r"^(\S+) RX command NB\+SOYMODE=1,1 OK", serial, re.M)]
    stops = [parse_time(value) for value in re.findall(
        r"^(\S+) TX NB\+SOYMODE=0,0", serial, re.M)]
    if len(starts) != 1:
        raise ValueError(f"Expected one acknowledged heating start, found {len(starts)}")
    stop_candidates = [value for value in stops if value > starts[0]]
    if not stop_candidates:
        raise ValueError("No stop command found after heating start")
    heat_start = starts[0]
    heat_stop = min(stop_candidates)

    motor_events = []
    motor_gear = None
    stopped_since = None
    for line in serial.splitlines():
        match = re.search(r"^(\S+).*?Usart: NoBush: (-?\d+)", line)
        if not match:
            continue
        stamp = parse_time(match.group(1))
        gear = int(match.group(2))
        if gear != motor_gear:
            motor_gear = gear
            stopped_since = stamp if gear == 0 else None
        motor_events.append((stamp, gear, stopped_since))
    if not motor_events:
        raise ValueError("No NoBush motor state records found in serial log")
    motor_times = [event[0] for event in motor_events]

    with csv_path.open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream))
    references = sorted(
        (parse_time(row["真实温度接收时间"]), float(row["真实温度℃"]))
        for row in rows
        if row["事件来源"] == "真实温度" and row["真实温度℃"])
    ref_times = [item[0] for item in references]
    phases = {"heating": [], "cooling": []}

    for row in rows:
        if row["事件来源"] != "NTC" or any(not row[column] for _, column in CHANNELS):
            continue
        stamp = parse_time(row["NTC接收时间"])
        if stamp < heat_start:
            continue
        motor_index = bisect_right(motor_times, stamp) - 1
        if motor_index < 0:
            continue
        _, gear, stopped_since = motor_events[motor_index]
        if (gear != 0 or stopped_since is None or
                (stamp - stopped_since).total_seconds() < MOTOR_STOP_SETTLE_SECONDS):
            continue
        phase = "heating" if stamp < heat_stop else "cooling"
        index = bisect_left(ref_times, stamp)
        if index == 0 or index == len(references):
            continue
        before, after = references[index - 1], references[index]
        gap = (after[0] - before[0]).total_seconds()
        if gap <= 0.0 or gap > MAX_REFERENCE_GAP_SECONDS:
            continue
        fraction = (stamp - before[0]).total_seconds() / gap
        temperature = before[1] + fraction * (after[1] - before[1])
        adcs = tuple(int(row[column]) for _, column in CHANNELS)
        if any(adc <= 0 for adc in adcs):
            continue
        phases[phase].append((stamp, temperature, *adcs))

    return phases


def calibration_samples(samples, channel_index):
    return [(sample[channel_index + 2], sample[1]) for sample in samples]


def describe_fit(name, samples):
    if len(samples) < 10:
        raise ValueError(f"Insufficient {name} samples after motor-stop filtering: {len(samples)}")
    training = [sample for index, sample in enumerate(samples) if index % 5 != 0]
    held_out = [sample for index, sample in enumerate(samples) if index % 5 == 0]
    table = make_table(training)
    errors = [predict(table, adc) - temperature for adc, temperature in held_out]
    absolute = sorted(abs(error) for error in errors)
    p95 = absolute[int(0.95 * (len(absolute) - 1))]
    rmse = math.sqrt(mean(error * error for error in errors))
    print(
        f"{name}: samples={len(samples)}, nodes={len(make_table(samples))}, "
        f"ADC={min(adc for adc, _ in samples):.1f}..{max(adc for adc, _ in samples):.1f}, "
        f"T={min(temp for _, temp in samples):.1f}..{max(temp for _, temp in samples):.1f} C, "
        f"holdout MAE={mean(absolute):.3f} C, RMSE={rmse:.3f} C, "
        f"P95={p95:.3f} C, max={max(absolute):.3f} C"
    )
    return make_table(samples)


def write_table(path, phase, channel_name, samples, table):
    lines = [
        f"/* Generated by calibrate_3ntc.py; {channel_name} {phase}; "
        f"motor stopped >= {MOTOR_STOP_SETTLE_SECONDS * 1000:.0f} ms; "
        "ADC ascending, temperature non-increasing. */"
    ]
    lines.extend(f"    {{{adc:.3f}f, {temperature:.3f}f}}," for adc, temperature in table)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_cooling_capture(csv_path, cooling_start_line=None):
    with csv_path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        numbered_rows = []
        for row in reader:
            numbered_rows.append((reader.line_num, row))
    rows = [row for _, row in numbered_rows]
    if (cooling_start_line is not None and
            not any(line_number == cooling_start_line
                    for line_number, _ in numbered_rows)):
        raise ValueError(
            f"Cooling start line {cooling_start_line} is not in the CSV")
    references = sorted(
        (parse_time(row["真实温度接收时间"]), float(row["真实温度℃"]))
        for row in rows
        if row["事件来源"] == "真实温度" and row["真实温度℃"])
    if len(references) < 5:
        raise ValueError("Insufficient reference-temperature samples")
    reference_times = [item[0] for item in references]
    peak_time, peak_temperature = max(references, key=lambda item: item[1])

    rpm_samples = sorted(
        (parse_time(row["站3快照接收时间"]),
         int(row["站3电机转速RPM"]))
        for row in rows
        if row["事件来源"] == "站3电机转速" and
        row["站3快照接收时间"] and row["站3电机转速RPM"])
    if not rpm_samples:
        raise ValueError("No station-3 RPM samples in the CSV")

    motor_states = []
    stopped_since = None
    previous_rpm = None
    previous_time = None
    for stamp, rpm in rpm_samples:
        sample_gap = ((stamp - previous_time).total_seconds()
                      if previous_time is not None else 0.0)
        if rpm != 0:
            stopped_since = None
        elif previous_rpm != 0 or sample_gap > MAX_RPM_SAMPLE_GAP_SECONDS:
            stopped_since = stamp
        motor_states.append((stamp, rpm, stopped_since))
        previous_rpm = rpm
        previous_time = stamp
    motor_times = [item[0] for item in motor_states]

    def reference_at(stamp):
        index = bisect_left(reference_times, stamp)
        if index == 0 or index == len(references):
            return None
        before, after = references[index - 1], references[index]
        gap = (after[0] - before[0]).total_seconds()
        if gap <= 0.0 or gap > MAX_REFERENCE_GAP_SECONDS:
            return None
        fraction = (stamp - before[0]).total_seconds() / gap
        return before[1] + fraction * (after[1] - before[1])

    def reference_slope(stamp):
        start = bisect_left(
            reference_times, stamp - timedelta(seconds=30))
        end = bisect_right(
            reference_times, stamp + timedelta(seconds=30))
        points = references[start:end]
        if len(points) < 5:
            return None
        x_values = [(point[0] - stamp).total_seconds()
                    for point in points]
        y_values = [point[1] for point in points]
        x_mean = mean(x_values)
        y_mean = mean(y_values)
        denominator = sum((x - x_mean) ** 2 for x in x_values)
        if denominator == 0.0:
            return None
        return sum((x - x_mean) * (y - y_mean)
                   for x, y in zip(x_values, y_values)) / denominator

    samples = []
    aligned_count = 0
    motor_stopped_count = 0
    for line_number, row in numbered_rows:
        if (row["事件来源"] != "NTC" or
                any(not row[column] for _, column in CHANNELS)):
            continue
        if (cooling_start_line is not None and
                line_number < cooling_start_line):
            continue
        stamp = parse_time(row["NTC接收时间"])
        if (cooling_start_line is None and stamp <= peak_time):
            continue
        temperature = reference_at(stamp)
        if temperature is None:
            continue
        aligned_count += 1
        motor_index = bisect_right(motor_times, stamp) - 1
        if motor_index < 0:
            continue
        motor_time, rpm, stopped_at = motor_states[motor_index]
        if (rpm != 0 or stopped_at is None or
                (stamp - motor_time).total_seconds() >
                MAX_RPM_SAMPLE_GAP_SECONDS or
                (stamp - stopped_at).total_seconds() <
                COOLING_MOTOR_STOP_SETTLE_SECONDS):
            continue
        motor_stopped_count += 1
        slope = reference_slope(stamp)
        if (slope is None or
                slope >= MAX_COOLING_REFERENCE_SLOPE_C_PER_SECOND):
            continue
        adcs = tuple(int(row[column]) for _, column in CHANNELS)
        if any(adc <= 0 for adc in adcs):
            continue
        samples.append((stamp, temperature, *adcs))

    if len(samples) < 10:
        raise ValueError(
            "Insufficient post-peak cooling samples with aligned reference "
            f"and RPM=0 for at least {COOLING_MOTOR_STOP_SETTLE_SECONDS * 1000:.0f} ms: "
            f"{len(samples)}")
    return samples, peak_time, peak_temperature, aligned_count, motor_stopped_count


def read_table(path):
    points = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.search(r"\{\s*([0-9.]+)f,\s*([0-9.]+)f\s*\}", line)
        if match:
            points.append((float(match[1]), float(match[2])))
    if len(points) < 2:
        raise ValueError(f"Existing table has fewer than two points: {path}")
    return points


def describe_cooling_fit(channel_name, samples, old_table):
    channel_index = CHANNELS.index((channel_name, f"{channel_name}_ADC"))
    channel_samples = [
        (sample[channel_index + 2], sample[1]) for sample in samples
    ]
    training = [
        sample for index, sample in enumerate(channel_samples)
        if index % 5 != 0
    ]
    held_out = [
        sample for index, sample in enumerate(channel_samples)
        if index % 5 == 0
    ]
    validation_table = make_table(training)
    errors = [
        predict(validation_table, adc) - temperature
        for adc, temperature in held_out
    ]
    absolute = sorted(abs(error) for error in errors)
    p95 = absolute[int(0.95 * (len(absolute) - 1))]
    first_sample_bin = min(adc for adc, _ in channel_samples) // 32
    last_sample_bin = max(adc for adc, _ in channel_samples) // 32
    prior_outside_range = [
        point for point in old_table
        if point[0] // 32 < first_sample_bin or
        point[0] // 32 > last_sample_bin
    ]
    table = make_table(prior_outside_range + channel_samples)
    print(
        f"cooling/{channel_name}: samples={len(channel_samples)}, "
        f"ADC={min(adc for adc, _ in channel_samples)}.."
        f"{max(adc for adc, _ in channel_samples)}, "
        f"T={min(temp for _, temp in channel_samples):.1f}.."
        f"{max(temp for _, temp in channel_samples):.1f} C, "
        f"holdout MAE={mean(absolute):.3f} C, "
        f"P95={p95:.3f} C, max={max(absolute):.3f} C "
        f"prior out-of-range nodes={len(prior_outside_range)}, "
        f"merged nodes={len(table)}"
    )
    return table


def write_cooling_table(path, channel_name, table, sample_count, source_name):
    lines = [
        f"/* Generated from {source_name}; {channel_name} cooling; "
        f"{sample_count} post-peak samples, RPM=0 for >=500 ms; "
        "merged with prior table outside measured ADC bins; "
        "ADC ascending, temperature non-increasing. */"
    ]
    lines.extend(
        f"    {{{adc:.3f}f, {temperature:.3f}f}},"
        for adc, temperature in table
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", type=Path)
    parser.add_argument("--serial", type=Path,
                        help="serial log (default: sibling <csv-stem>-serial.txt)")
    parser.add_argument("--write", action="store_true",
                        help="write six independent tables under tables/NTC3")
    parser.add_argument(
        "--cooling-only", action="store_true",
        help="fit post-peak cooling tables from CSV RPM and temperature data")
    parser.add_argument(
        "--cooling-start-line", type=int,
        help="use this 1-based physical CSV line as the cooling boundary "
             "(includes the header as line 1)")
    args = parser.parse_args()
    output_dir = Path(__file__).resolve().parents[2] / "tables" / "NTC3"
    if args.cooling_start_line is not None and not args.cooling_only:
        parser.error("--cooling-start-line requires --cooling-only")
    if args.cooling_only:
        samples, peak_time, peak_temperature, aligned_count, stopped_count = \
            read_cooling_capture(args.csv, args.cooling_start_line)
        selection = (
            "aligned cooling NTC records"
            if args.cooling_start_line is not None
            else "aligned post-peak NTC records"
        )
        print(
            f"Cooling capture: peak={peak_temperature:.1f} C at "
            f"{peak_time.isoformat()}, {selection}={aligned_count}, "
            f"motor stopped >=500 ms={stopped_count}, "
            f"cooling fit samples={len(samples)}"
        )
        if args.cooling_start_line is not None:
            print(
                f"Cooling samples start at physical CSV line "
                f"{args.cooling_start_line} (header is line 1)"
            )
        for channel_name, _ in CHANNELS:
            path = output_dir / (
                f"ntcTemp_machine3_{channel_name.lower()}_cooling_table.inc")
            old_table = read_table(path)
            table = describe_cooling_fit(channel_name, samples, old_table)
            if args.write:
                write_cooling_table(
                    path, channel_name, table, len(samples), args.csv.name)
                print(f"  wrote {path.name}")
        return

    serial_path = args.serial or args.csv.with_name(args.csv.stem + "-serial.txt")
    phases = read_phases(args.csv, serial_path)
    if args.write:
        output_dir.mkdir(parents=True, exist_ok=True)

    for phase, records in phases.items():
        if not records:
            raise ValueError(f"No aligned {phase} samples")
        phase_start = records[0][0]
        phase_end = records[-1][0]
        print(f"{phase}: {phase_start.isoformat()} .. {phase_end.isoformat()}, raw samples={len(records)}")
        for channel_index, (channel_name, _) in enumerate(CHANNELS):
            samples = calibration_samples(records, channel_index)
            table = describe_fit(f"{phase}/{channel_name}", samples)
            if args.write:
                filename = f"ntcTemp_machine3_{channel_name.lower()}_{phase}_table.inc"
                write_table(output_dir / filename, phase, channel_name, samples, table)
                print(f"  wrote {filename}")


if __name__ == "__main__":
    main()
